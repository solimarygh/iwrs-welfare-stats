# Builds the data file read by the static site (site/data.js) from the processed
# tables, so the site can be regenerated after every yearly update.

site_labels <- function() {
  list(
    taxa = c(ALL_INVERTEBRATES = "All invertebrates", ALL_ARTHROPODS = "All arthropods",
             insects = "Insects", crustaceans = "Crustaceans",
             other_arthropods = "Other arthropods (spiders, mites, ...)",
             arthropods_general = "Arthropods (generic term)",
             cephalopods = "Cephalopods", other_molluscs = "Other molluscs",
             other_invertebrates = "Other invertebrates (worms, ...)",
             invertebrates_general = "Invertebrates (generic term)"),
    states = c(sentience = "Sentience", affect_emotion = "Affect and emotion",
               consciousness = "Consciousness", welfare = "Welfare",
               nociception_pain = "Nociception and pain"))
}

# `counts`: data.frame read from data/processed/counts_by_year.csv.
build_site_data <- function(counts, run_date) {
  lab <- site_labels()
  stopifnot(all(counts$taxon_group %in% names(lab$taxa)),
            all(counts$state_block %in% c(names(lab$states), "ANY", "NONE")),
            !anyNA(counts$n), !anyNA(counts$year))
  taxa <- unique(counts[, c("taxon_group", "is_arthropod")])
  taxa <- taxa[match(intersect(names(lab$taxa), taxa$taxon_group), taxa$taxon_group), ]
  partial <- unique(counts$year[counts$partial_year])
  all_works <- unique(counts[, c("year", "n_all_works")])
  list(
    meta = list(run_date = run_date, first_year = min(counts$year), last_year = max(counts$year),
                partial_year = if (length(partial)) max(partial) else NULL,
                source = "OpenAlex"),
    taxa = data.frame(key = taxa$taxon_group, label = unname(lab$taxa[taxa$taxon_group]),
                      arthropod = taxa$is_arthropod, stringsAsFactors = FALSE),
    states = data.frame(key = names(lab$states), label = unname(lab$states), stringsAsFactors = FALSE),
    rows = data.frame(taxon = counts$taxon_group, state = counts$state_block,
                      year = counts$year, n = counts$n, stringsAsFactors = FALSE),
    all_works = data.frame(year = all_works$year, n = all_works$n_all_works)
  )
}

# Site data from the strict (core) counts: blocks and ANY come from the records, and NONE (all papers
# on the taxon group, with no state term) comes from the OpenAlex counts of script 01.
build_site_data_core <- function(core, api, run_date) {
  lab <- site_labels()
  stopifnot(all(core$taxon_group %in% names(lab$taxa)), !anyNA(core$n), !anyNA(api$n))
  blocks <- c(names(lab$states), "ANY")
  rows <- rbind(core[core$state_block %in% blocks, c("taxon_group", "is_arthropod", "state_block", "year", "n", "partial_year")],
                api[api$state_block == "NONE" & api$taxon_group %in% core$taxon_group, c("taxon_group", "is_arthropod", "state_block", "year", "n", "partial_year")])
  rows$n_all_works <- api$n_all_works[match(rows$year, api$year)]
  stopifnot(!anyNA(rows$n_all_works))
  out <- build_site_data(rows, run_date)
  out$meta$definition <- "core"
  out
}

write_site_data <- function(x, path = "site/data.js") {
  dir.create(dirname(path), showWarnings = FALSE, recursive = TRUE)
  json <- jsonlite::toJSON(x, auto_unbox = TRUE, dataframe = "rows", null = "null", digits = NA)
  writeLines(paste0("// Generated by scripts/05_build_site_data.R. Do not edit by hand.\n",
                    "window.IWRS_DATA = ", json, ";"), path, useBytes = TRUE)
}
