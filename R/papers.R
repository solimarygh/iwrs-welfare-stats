# List of the core papers (no abstract: abstracts are publisher text and stay out of the published files)
# and the part of it that the site shows: the papers of the latest year.

# One row per core paper. `authors` comes from fetch_authors(); `taxa` lists the taxon groups of the paper
# (plus ALL_ARTHROPODS for arthropods) and `themes` its core blocks, separated by ";".
build_papers_table <- function(rec, authors, cfg) {
  core <- rec[rec$core_any, , drop = FALSE]
  collapse_flags <- function(m) apply(m, 1, function(r) paste(colnames(m)[r], collapse = ";"))
  tx <- as.matrix(core[paste0("taxon_", names(cfg$taxa))]); colnames(tx) <- names(cfg$taxa)
  th <- as.matrix(core[paste0("core_", names(cfg$core$states))]); colnames(th) <- names(cfg$core$states)
  taxa <- collapse_flags(tx)
  taxa[core$is_arthropod] <- paste0(taxa[core$is_arthropod], ifelse(nzchar(taxa[core$is_arthropod]), ";", ""), "ALL_ARTHROPODS")
  out <- data.frame(
    openalex_id = core$openalex_id, doi = core$doi, year = core$year, title = core$title,
    authors = authors$authors[match(core$openalex_id, authors$openalex_id)],
    journal = core$source_name, journal_group = journal_group_of(core$source_name, cfg),
    type = core$type, language = core$language, cited_by_count = core$cited_by_count,
    taxa = taxa, themes = collapse_flags(th), stringsAsFactors = FALSE)
  out[order(-out$year, out$journal, out$title), ]
}

# What the page needs for the list: the papers of `year`, authors cut after `max_authors`.
# `review`: optional data.frame(openalex_id, final) from scripts/11_read_review.R (final label 0, 1 or 2 of the
# papers reviewed by hand; NA while a disagreement is open). A paper without a label is "not reviewed".
papers_site_data <- function(tbl, year, run_date, max_authors = 6, review = NULL) {
  x <- tbl[tbl$year == year, , drop = FALSE]
  cut <- function(a) vapply(a, function(z) {
    if (is.na(z) || !nzchar(z)) return("")
    v <- strsplit(z, "; ", fixed = TRUE)[[1]]
    if (length(v) > max_authors) paste0(paste(v[seq_len(max_authors)], collapse = ", "), ", et al.") else paste(v, collapse = ", ")
  }, "", USE.NAMES = FALSE)
  items <- data.frame(title = x$title, authors = cut(x$authors), journal = ifelse(is.na(x$journal), "", x$journal),
                      doi = ifelse(is.na(x$doi), "", x$doi), id = x$openalex_id,
                      taxa = x$taxa, themes = x$themes, stringsAsFactors = FALSE)
  if (!is.null(review)) {
    lab <- review$final[match(items$id, review$openalex_id)]
    items$review <- ifelse(is.na(lab), "", lab)
  }
  list(year = year, as_of = run_date, reviewed = !is.null(review) && any(items$review != ""), items = items)
}

write_papers_js <- function(data, path = "site/papers.js") {
  json <- jsonlite::toJSON(data, auto_unbox = TRUE, dataframe = "rows", na = "null")
  writeLines(c("// Generated by scripts/09_build_papers.R. Do not edit by hand.", paste0("window.IWRS_PAPERS = ", json, ";")), path, useBytes = TRUE)
}
