# Distribution of the core papers across groups of journals.

# Group key of each journal name (first matching group wins; "other" when none matches).
journal_group_of <- function(names, cfg) {
  nm <- tolower(trimws(ifelse(is.na(names), "", names)))
  key <- rep("other", length(nm))
  for (g in rev(cfg$journals$groups)) {            # reversed so that the first group has the last word
    hit <- Reduce(`|`, lapply(unlist(g$patterns), function(p) grepl(p, nm, perl = TRUE)), FALSE)
    key[hit] <- g$key
  }
  key
}

journal_group_labels <- function(cfg) {
  c(setNames(vapply(cfg$journals$groups, function(g) g$label, ""), vapply(cfg$journals$groups, function(g) g$key, "")),
    other = cfg$journals$other_label)
}

# Counts of core papers per taxon group x journal group x year, and the most frequent journals
# of each taxon group with their count per year.
journal_tables <- function(rec, cfg) {
  years <- seq(cfg$project$years[1], cfg$project$years[2])
  rec <- rec[rec$core_any, , drop = FALSE]
  rec$jgroup <- journal_group_of(rec$source_name, cfg)
  jkeys <- names(journal_group_labels(cfg))
  taxa <- c(names(cfg$taxa), "ALL_ARTHROPODS", "ALL_INVERTEBRATES")
  flag <- function(g) switch(g, ALL_ARTHROPODS = rec$is_arthropod, ALL_INVERTEBRATES = rep(TRUE, nrow(rec)), rec[[paste0("taxon_", g)]])
  by_year <- do.call(rbind, lapply(taxa, function(g) {
    sel <- rec[flag(g), , drop = FALSE]
    do.call(rbind, lapply(jkeys, function(k) data.frame(
      taxon = g, group = k, year = years,
      n = tabulate(match(sel$year[sel$jgroup == k], years), nbins = length(years)), stringsAsFactors = FALSE)))
  }))
  top <- do.call(rbind, lapply(taxa, function(g) {
    sel <- rec[flag(g), , drop = FALSE]
    tb <- sort(table(sel$source_name[!is.na(sel$source_name) & nzchar(sel$source_name)]), decreasing = TRUE)
    nm <- names(tb)[seq_len(min(cfg$journals$top_n, length(tb)))]
    if (!length(nm)) return(NULL)
    data.frame(taxon = g, journal = nm, group = journal_group_of(nm, cfg),
               counts = I(lapply(nm, function(j) tabulate(match(sel$year[sel$source_name == j], years), nbins = length(years)))),
               stringsAsFactors = FALSE)
  }))
  list(by_year = by_year, top = top, years = years)
}

write_journals_data <- function(tabs, cfg, path = "site/journals.js") {
  lab <- journal_group_labels(cfg)
  out <- list(years = tabs$years,
              groups = data.frame(key = names(lab), label = unname(lab), stringsAsFactors = FALSE),
              rows = tabs$by_year,
              top = lapply(split(tabs$top, tabs$top$taxon), function(d)
                lapply(seq_len(nrow(d)), function(i) list(journal = d$journal[i], group = d$group[i], counts = d$counts[[i]]))))
  json <- jsonlite::toJSON(out, auto_unbox = TRUE, dataframe = "rows", digits = NA)
  writeLines(paste0("// Generated by scripts/07_journal_distribution.R. Do not edit by hand.\n",
                    "window.IWRS_JOURNALS = ", json, ";"), path, useBytes = TRUE)
}
