/* ---------- scales ---------- */
function niceScale(max) {
  const raw = Math.max(max, 1) / 4, mag = Math.pow(10, Math.floor(Math.log10(raw))), norm = raw / mag;
  const step = (norm <= 1 ? 1 : norm <= 2 ? 2 : norm <= 5 ? 5 : 10) * mag;
  const top = Math.ceil(max / step - 1e-9) * step || step;
  const ticks = []; for (let v = 0; v <= top + step * 1e-6; v += step) ticks.push(v);
  return { top, ticks };
}

/* ---------- tooltip ---------- */
function makeTip(host) {
  const tip = h('div', { class: 'tip', role: 'status' });
  host.appendChild(tip);
  return {
    el: tip,
    show(html, px, py, k) {
      tip.replaceChildren(...html);
      tip.classList.add('on');
      const w = tip.offsetWidth, hostW = host.clientWidth;
      let left = px * k + 14;
      if (left + w > hostW) left = Math.max(0, px * k - w - 14);
      tip.style.left = left + 'px'; tip.style.top = py * k + 'px';
    },
    hide() { tip.classList.remove('on'); }
  };
}

/* ---------- line chart ---------- */
function drawLines(host, o) {
  host.replaceChildren();
  const W = Math.max(host.clientWidth, 280), H = W < 520 ? 250 : 310;
  const m = { t: 20, r: 22, b: 30, l: 48 };
  const iw = W - m.l - m.r, ih = H - m.t - m.b, n = o.years.length;
  const sc = niceScale(Math.max(...o.series.flatMap(x => x.values), o.ref || 0));
  const compact = sc.top >= 10000;
  const tickFmt = v => compact ? (v / 1000).toLocaleString('en-US') + 'K' : fmt(v);
  const X = i => n === 1 ? m.l + iw / 2 : m.l + (i * iw) / (n - 1);
  const Y = v => m.t + ih - (v / sc.top) * ih;
  const svg = s('svg', { viewBox: `0 0 ${W} ${H}`, role: 'img', 'aria-label': o.aria, tabindex: 0 }, host);

  sc.ticks.forEach(t => {
    s('line', { class: 'grid', x1: m.l, x2: W - m.r, y1: Y(t), y2: Y(t) }, svg);
    s('text', { class: 'tick', x: m.l - 10, y: Y(t) + 4, 'text-anchor': 'end' }, svg).textContent = tickFmt(t);
  });
  const pi = o.years.indexOf(o.partialYear);
  if (pi >= 0) {
    const half = n > 1 ? iw / (n - 1) / 2 : 20;
    const x0 = Math.max(m.l, X(pi) - half), x1 = Math.min(W - 6, X(pi) + half);
    s('rect', { class: 'band', x: x0, y: m.t, width: x1 - x0, height: ih }, svg);
    if (x1 - x0 >= 52) s('text', { class: 'band-label', x: (x0 + x1) / 2, y: m.t + 14, 'text-anchor': 'middle' }, svg).textContent = 'partial year';
  }
  s('line', { class: 'axis', x1: m.l, x2: W - m.r, y1: Y(0), y2: Y(0) }, svg);
  if (o.ref) {
    s('line', { class: 'axis', x1: m.l, x2: W - m.r, y1: Y(o.ref), y2: Y(o.ref) }, svg);
    s('text', { class: 'tick', x: m.l + 4, y: Y(o.ref) - 6 }, svg).textContent = o.refLabel;
  }
  const step = iw / n < 38 ? 2 : 1;
  o.years.forEach((yr, i) => { if ((n - 1 - i) % step === 0)
    s('text', { class: 'tick', x: X(i), y: H - 8, 'text-anchor': 'middle' }, svg).textContent = yr; });

  const paths = [];
  // The partial year is drawn as a lone hollow marker: joining it to the line would read as a drop.
  const nc = (pi >= 0 && pi === n - 1) ? n - 1 : n;
  o.series.forEach(se => {
    const color = `var(--s${se.slot})`, vals = se.values.slice(0, nc);
    const d = vals.map((v, i) => `${i ? 'L' : 'M'}${X(i).toFixed(1)},${Y(v).toFixed(1)}`).join('');
    if (o.series.length === 1 && nc > 0)
      s('path', { d: `${d}L${X(nc - 1).toFixed(1)},${Y(0)}L${X(0).toFixed(1)},${Y(0)}Z`, style: `fill:${color};opacity:.10` }, svg);
    paths.push(s('path', { d, class: 'line', style: `stroke:${color}` }, svg));
    if (nc > 0) s('circle', { cx: X(nc - 1), cy: Y(vals[nc - 1]), r: 4, style: `fill:${color};stroke:var(--surface);stroke-width:2` }, svg);
    if (nc < n) s('circle', { cx: X(n - 1), cy: Y(se.values[n - 1]), r: 4, style: `fill:var(--surface);stroke:${color};stroke-width:2` }, svg);
  });
  if (o.series.length === 1 && nc > 0) {   // selective direct labels: first and last complete value
    const se = o.series[0];
    [...new Set([0, nc - 1])].forEach(i => {
      let ty = Y(se.values[i]) - 11; if (ty < 12) ty = Y(se.values[i]) + 20;
      s('text', { class: 'dlabel', x: X(i), y: ty, 'text-anchor': i === 0 ? 'start' : (i === n - 1 ? 'end' : 'middle') }, svg).textContent = o.fmtVal(se.values[i]);
    });
  }
  if (o.animate && !reduceMotion) paths.forEach(p => {
    const L = p.getTotalLength(); p.style.strokeDasharray = L; p.style.strokeDashoffset = L;
    requestAnimationFrame(() => requestAnimationFrame(() => { p.style.transition = 'stroke-dashoffset 900ms ease'; p.style.strokeDashoffset = 0; }));
    p.addEventListener('transitionend', () => { p.style.strokeDasharray = 'none'; }, { once: true });
  });

  /* hover / keyboard layer */
  const cross = s('line', { class: 'cross', y1: m.t, y2: m.t + ih, style: 'display:none' }, svg);
  const dots = o.series.map(se => s('circle', { r: 4, style: `display:none;fill:var(--s${se.slot});stroke:var(--surface);stroke-width:2` }, svg));
  const hit = s('rect', { x: m.l - 10, y: m.t, width: iw + 20, height: ih, fill: 'transparent' }, svg);
  const tip = makeTip(host);
  let cur = n - 1;
  const k = () => svg.getBoundingClientRect().width / W || 1;
  function show(i) {
    cur = Math.max(0, Math.min(n - 1, i));
    const cx = X(cur);
    cross.setAttribute('x1', cx); cross.setAttribute('x2', cx); cross.style.display = '';
    dots.forEach((d, j) => { d.setAttribute('cx', cx); d.setAttribute('cy', Y(o.series[j].values[cur])); d.style.display = ''; });
    const head = h('p', { class: 'tip-head', text: o.years[cur] + (o.years[cur] === o.partialYear ? ' (partial year)' : '') });
    const rows = o.series.map(se => h('div', { class: 'tip-row' },
      h('span', { class: 'tip-key', style: `border-color:var(--s${se.slot})` }),
      h('span', { class: 'tip-name', text: se.label }),
      h('span', { class: 'tip-val', text: o.fmtVal(se.values[cur]) })));
    tip.show([head, ...rows], cx, m.t, k());
  }
  function hide() { cross.style.display = 'none'; dots.forEach(d => d.style.display = 'none'); tip.hide(); }
  hit.addEventListener('pointermove', e => {
    const r = svg.getBoundingClientRect(), px = (e.clientX - r.left) / k();
    show(n === 1 ? 0 : Math.round((px - m.l) / (iw / (n - 1))));
  });
  hit.addEventListener('pointerleave', hide);
  svg.addEventListener('focus', () => show(cur));
  svg.addEventListener('blur', hide);
  svg.addEventListener('keydown', e => {
    const map = { ArrowLeft: cur - 1, ArrowRight: cur + 1, Home: 0, End: n - 1 };
    if (e.key in map) { e.preventDefault(); show(map[e.key]); } else if (e.key === 'Escape') hide();
  });
}

