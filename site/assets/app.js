const idx = new Map();
D.rows.forEach(r => idx.set(`${r.taxon}|${r.state}|${r.year}`, r.n));
const val = (t, st, y) => idx.get(`${t}|${st}|${y}`) || 0;
const first = D.meta.first_year, partial = D.meta.partial_year;
const lastComplete = partial ? partial - 1 : D.meta.last_year;
