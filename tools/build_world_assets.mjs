// Builds two static assets from public-domain / open data. Run rarely (the outputs are committed):
//   mkdir /tmp/geo && cd /tmp/geo && npm init -y && npm install world-atlas topojson-client i18n-iso-countries diacritics
//   node /path/to/tools/build_world_assets.mjs /path/to/repo
// Outputs:
//   site/assets/world.js              country outlines (Natural Earth 110m via world-atlas, public domain),
//                                     Equal Earth projection, one SVG path + a label point per country
//   data/reference/country_names.csv  normalised country names (en, es, pt + common aliases) -> ISO3
import { createRequire } from 'module';
import fs from 'fs';
const require = createRequire(process.cwd() + '/');
const topo = require('topojson-client'), world = require('world-atlas/countries-110m.json');
const iso = require('i18n-iso-countries'), strip = require('diacritics').remove;
for (const l of ['en', 'es', 'pt']) iso.registerLocale(require(`i18n-iso-countries/langs/${l}.json`));
const repo = process.argv[2] || '.';

// ---- outlines ------------------------------------------------------------------------------------
const A1 = 1.340264, A2 = -0.081106, A3 = 0.000893, A4 = 0.003796, M = Math.sqrt(3) / 2;
function equalEarth([lon, lat]) {
  const l = lon * Math.PI / 180, p = lat * Math.PI / 180, th = Math.asin(M * Math.sin(p)), t2 = th * th, t6 = t2 ** 3;
  return [l * Math.cos(th) / (M * (A1 + 3 * A2 * t2 + t6 * (7 * A3 + 9 * A4 * t2))), -th * (A1 + A2 * t2 + t6 * (A3 + A4 * t2))];
}
const feats = topo.feature(world, world.objects.countries).features.filter(f => f.id !== '010'); // no Antarctica
const polys = f => f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates;
let minX = 1e9, minY = 1e9, maxX = -1e9, maxY = -1e9;
const proj = feats.map(f => ({ f, polys: polys(f).map(poly => poly.map(ring => ring.map(equalEarth))) }));
for (const c of proj) for (const poly of c.polys) for (const ring of poly) for (const [x, y] of ring) {
  minX = Math.min(minX, x); maxX = Math.max(maxX, x); minY = Math.min(minY, y); maxY = Math.max(maxY, y); }
const W = 1000, k = W / (maxX - minX), H = Math.round((maxY - minY) * k);
const sx = ([x, y]) => [(x - minX) * k, (y - minY) * k];
const area = r => { let a = 0; for (let i = 0; i < r.length; i++) { const [x1, y1] = r[i], [x2, y2] = r[(i + 1) % r.length]; a += x1 * y2 - x2 * y1; } return a / 2; };
const centroid = r => { let a = area(r), cx = 0, cy = 0; if (!a) return r[0];
  for (let i = 0; i < r.length; i++) { const [x1, y1] = r[i], [x2, y2] = r[(i + 1) % r.length], c = x1 * y2 - x2 * y1; cx += (x1 + x2) * c; cy += (y1 + y2) * c; }
  return [cx / (6 * a), cy / (6 * a)]; };
const countries = [];
for (const { f, polys: pp } of proj) {
  const id = iso.numericToAlpha3(f.id); if (!id) continue;
  let d = '', best = null, bestA = 0;
  for (const poly of pp) for (const [i, ring0] of poly.entries()) {
    const ring = ring0.map(sx);
    d += 'M' + ring.map(([x, y], j) => { const p = `${x.toFixed(1)},${y.toFixed(1)}`; return p; }).join('L') + 'Z';
    if (i === 0 && Math.abs(area(ring)) > bestA) { bestA = Math.abs(area(ring)); best = ring; }
  }
  const [cx, cy] = centroid(best);
  countries.push({ id, name: f.properties.name, d, cx: +cx.toFixed(1), cy: +cy.toFixed(1) });
}
fs.writeFileSync(`${repo}/site/assets/world.js`,
  `// Generated by tools/build_world_assets.mjs. Natural Earth 110m (public domain) via world-atlas, Equal Earth projection.\n` +
  `window.IWRS_WORLD = ${JSON.stringify({ width: W, height: H, countries })};\n`);
console.log('world.js:', countries.length, 'countries,', W + 'x' + H);

// ---- country names -> ISO3 ----------------------------------------------------------------------------
const norm = s => strip(String(s)).toLowerCase().replace(/[^a-z0-9]+/g, ' ').trim();
const aliases = {
  USA: ['usa', 'us', 'u s a', 'u s', 'united states', 'united states of america', 'estados unidos', 'eeuu', 'ee uu', 'eua', 'estados unidos da america', 'estados unidos de america'],
  GBR: ['uk', 'u k', 'great britain', 'england', 'scotland', 'wales', 'northern ireland', 'united kingdom', 'reino unido', 'inglaterra', 'escocia', 'gales', 'gra bretanha'],
  RUS: ['russia', 'rusia', 'russian federation', 'federacao russa'], KOR: ['south korea', 'korea', 'republic of korea', 'corea del sur', 'coreia do sul'],
  PRK: ['north korea', 'corea del norte', 'coreia do norte'], CZE: ['czechia', 'czech republic', 'republica checa', 'tchequia'],
  CIV: ['ivory coast', 'cote d ivoire', 'costa de marfil', 'costa do marfim'], TUR: ['turkey', 'turkiye', 'turquia'], IRN: ['iran'],
  VNM: ['vietnam', 'viet nam'], MEX: ['mexico', 'mejico'], BOL: ['bolivia'], VEN: ['venezuela'], TWN: ['taiwan'], HKG: ['hong kong'],
  SYR: ['syria'], LAO: ['laos'], MDA: ['moldova'], TZA: ['tanzania'], SWZ: ['swaziland', 'eswatini'], MMR: ['burma', 'myanmar'],
  CPV: ['cape verde', 'cabo verde'], TLS: ['east timor', 'timor leste'], PSE: ['palestine'], NLD: ['holland', 'the netherlands', 'netherlands', 'paises bajos', 'holanda', 'paises baixos'],
  DEU: ['germany', 'deutschland', 'alemania', 'alemanha'], ARE: ['uae', 'emirates', 'united arab emirates', 'emiratos arabes unidos'],
  ZAF: ['south africa', 'sudafrica', 'africa do sul'], NZL: ['new zealand', 'nueva zelanda', 'nova zelandia'], BRA: ['brasil', 'brazil'],
  CHN: ['china', 'pr china', 'people s republic of china'], COD: ['dr congo', 'drc', 'democratic republic of the congo'], COG: ['congo brazzaville'],
};
const rows = new Map(), conflicts = [];
const add = (name, a3, en) => { const n = norm(name); if (!n) return;
  if (rows.has(n) && rows.get(n).iso3 !== a3) { conflicts.push(`${n}: ${rows.get(n).iso3} vs ${a3}`); return; }
  rows.set(n, { iso3: a3, en }); };
for (const a2 of Object.keys(iso.getAlpha2Codes())) {
  const a3 = iso.alpha2ToAlpha3(a2), en = iso.getName(a2, 'en');
  for (const l of ['en', 'es', 'pt']) { const all = iso.getName(a2, l, { select: 'all' }) || []; (Array.isArray(all) ? all : [all]).forEach(n => add(n, a3, en)); }
  add(a3, a3, en); add(a2, a3, en);
}
for (const [a3, list] of Object.entries(aliases)) { const en = iso.getName(iso.alpha3ToAlpha2(a3), 'en'); list.forEach(n => add(n, a3, en)); }
const csv = ['name_norm,iso3,country'].concat([...rows.entries()].sort().map(([n, v]) => `${n},${v.iso3},"${v.country || v.en}"`));
fs.writeFileSync(`${repo}/data/reference/country_names.csv`, csv.join('\n') + '\n');
console.log('country_names.csv:', rows.size, 'names; conflicts:', conflicts.length, conflicts.slice(0, 8));
